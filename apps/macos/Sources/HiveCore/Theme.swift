import CGhosttyVT

/// Default colors for mirrors. The default is Tomorrow Night, which is what
/// the maintainer's Ghostty and tmux use.
public struct Theme: Sendable, Equatable {
    public var foreground: RGB
    public var background: RGB
    public var cursor: RGB
    public var selection: RGB
    public var palette: [RGB] // 16

    public static let tomorrowNight = Theme(
        foreground: RGB(0xc5, 0xc8, 0xc6), background: RGB(0x1d, 0x1f, 0x21), cursor: RGB(0xc5, 0xc8, 0xc6),
        selection: RGB(0x37, 0x3b, 0x41),
        palette: [
            RGB(0x1d, 0x1f, 0x21), RGB(0xcc, 0x66, 0x66), RGB(0xb5, 0xbd, 0x68), RGB(0xf0, 0xc6, 0x74),
            RGB(0x81, 0xa2, 0xbe), RGB(0xb2, 0x94, 0xbb), RGB(0x8a, 0xbe, 0xb7), RGB(0xc5, 0xc8, 0xc6),
            RGB(0x96, 0x98, 0x96), RGB(0xcc, 0x66, 0x66), RGB(0xb5, 0xbd, 0x68), RGB(0xf0, 0xc6, 0x74),
            RGB(0x81, 0xa2, 0xbe), RGB(0xb2, 0x94, 0xbb), RGB(0x8a, 0xbe, 0xb7), RGB(0xff, 0xff, 0xff),
        ])
}

extension RGB {
    var c: GhosttyColorRgb { GhosttyColorRgb(r: r, g: g, b: b) }
}
