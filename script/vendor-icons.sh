#!/bin/sh
# Regenerates the vendor icons: each program's own icon, from its vendor's
# site, pinned by SHA-256. A vendor changing their artwork fails this script
# until someone looks at the new icon and updates the pin.
#   apps/macos/Sources/HiveCore/VendorIcons.generated.swift  (96 px PNGs)
#   script/notices/vendor-icons.txt                          (sources)
# Columns: name, background behind a transparent mark ("-": the icon fills
# its cell), title, SHA-256, URL.
set -eu
manifest='
claude   - Claude~Code 9b1fa78fa1d19195076f30cd386a76c51688fee7b36eb1af51a87c68548d20cf https://code.claude.com/docs/_mintlify/favicons/claude-code/pLsy-mRpNksna2sx/_generated/favicon/apple-touch-icon.png
codex    - Codex 8d5575ee667ff715cd3e3074d5296edc68d5aadd89720d203e13131b68b22a04 https://developers.openai.com/favicon.png
gemini   - Gemini~CLI 351e9f5b1bf863d738cd7be4ed040a625a1419450ae7fc490143e4042b7c2438 https://geminicli.com/icon.png
grok     - Grok a3487e9bfbe49df853c51c5bdbf980bfb3bec782bfdd398a9bf333bb648b832f https://grok.com/images/apple-touch-icon.png
opencode - OpenCode 2f2d5687a641f7fc1c3931072249a5984660375c091064fe8b374e4e43a8656c https://opencode.ai/apple-touch-icon-v3.png
ollama   FFFFFF Ollama 8a5d4f0444d756d1d64c6615eb163ecd71fba180bd07c4199e88461c921778d1 https://ollama.com/public/apple-touch-icon.png
python   FFFFFF Python bb471012989f8309826369d2d20415aced04fb98336d755a1c53a9123e5e7a6f https://www.python.org/static/apple-touch-icon-144x144-precomposed.png
bun      FBF0DF Bun d4ee2d7902b652b5205f9f53f7ccb3455cf6386cbc2fedcb133db05dd7a771b4 https://bun.sh/icons/apple-touch-icon.png
go       - Go 8bf938ca7a737e0478cd119c920e93943f6fb8562e21461aa5030cf0597fc107 https://go.dev/images/favicon-gopher-plain.png
rust     FFFFFF Rust 2c6257567a5a77975af9286e352c416fb8da20709d02eb0dc7a2b524c0d858dc https://rust-lang.org/static/images/apple-touch-icon.png
docker   FFFFFF Docker 5cb5caeeef34a0979a0b21640ea6bbbfb8345a9fff0d0e910c345ce4d0b65718 https://www.docker.com/app/uploads/2024/02/cropped-docker-logo-favicon-180x180.png
'
root="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d "${TMPDIR:-/tmp}/hive-vendor.XXXXXX")"
trap 'rm -rf "$work"' EXIT
ua='Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Safari/605.1.15'
swift="$work/swift"; notice="$work/notice"; : > "$swift"; : > "$notice"
echo "$manifest" | while read -r name bg title sha url; do
  [ -n "$name" ] || continue
  title=$(echo "$title" | tr '~' ' ')
  curl -sfL -A "$ua" --max-time 30 -o "$work/$name.in" "$url"
  got=$(shasum -a 256 "$work/$name.in" | cut -c1-64)
  [ "$got" = "$sha" ] || { echo "$name: the vendor's icon changed ($got). Look at it, then update the pin." >&2; exit 1; }
  # PNG at most 96 px: crisp at 24 pt on Retina, small in the binary.
  sips -s format png "$work/$name.in" --out "$work/$name.png" >/dev/null
  w=$(sips -g pixelWidth "$work/$name.png" | awk '/pixelWidth/ {print $2}')
  [ "$w" -gt 96 ] && sips -Z 96 "$work/$name.png" >/dev/null
  b64=$(base64 < "$work/$name.png" | tr -d '\n')
  [ "$bg" = - ] && back=nil || back="0x$bg"
  printf '        "%s": VendorIcon(title: "%s", background: %s, png: "%s"),\n' "$name" "$title" "$back" "$b64" >> "$swift"
  printf '%s: %s\n' "$title" "$url" >> "$notice"
done
{
  echo "// Generated by script/vendor-icons.sh from each vendor's site. Do not edit."
  echo "// Sources: script/notices/vendor-icons.txt."
  echo
  echo "extension VendorIcon {"
  echo "    public static let all: [String: VendorIcon] = ["
  cat "$swift"
  echo "    ]"
  echo "}"
} > "$root/apps/macos/Sources/HiveCore/VendorIcons.generated.swift"
{
  echo "Vendor icons"
  echo "============"
  echo
  echo "Hive.app shows these icons only to name the program running in a pane."
  echo "Each is its owner's artwork and trademark, taken from the owner's site"
  echo "below, scaled down and otherwise unmodified. They are not covered by"
  echo "hive's MIT licence."
  echo
  cat "$notice"
} > "$root/script/notices/vendor-icons.txt"
echo "vendor icons: $(grep -c . "$notice")"
