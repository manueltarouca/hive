#!/bin/sh
# Regenerates the program icons from a pinned Simple Icons release:
#   apps/macos/Sources/HiveCore/Icons.generated.swift  (path data, colours)
#   script/notices/icons.txt                           (per-icon licences)
# One run writes both, so the pin, the data and the notice can't drift.
# Only SVG and JSON are read from the package; nothing in it is run.
set -eu
version=16.35.0
integrity="sha512-TCfl/2+GTrx0nCo4pEWGvxhOb8c6NsqOU1OpwjtF4lwJAthB8IYVD0fuIMjLMg6JFuG1YBO0t1iETQqJLqkoJA=="
# Brand logos hive shows, only to name the program in a pane. Left out on
# purpose: GPL artwork (Emacs, fish), MIT artwork whose copyright line the
# data doesn't carry (Deno, Bash), and Gemini and Terraform, whose owners
# restrict use of their logos.
slugs="bun claude docker elixir git go helix htop kotlin kubernetes lua mysql neovim nodedotjs ollama opencode opentofu perl php postgresql python redis ruby rust sqlite swift tmux vim zig zsh"

root="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d "${TMPDIR:-/tmp}/hive-icons.XXXXXX")"
trap 'rm -rf "$work"' EXIT
curl -sfL "https://registry.npmjs.org/simple-icons/-/simple-icons-$version.tgz" -o "$work/si.tgz"
got="sha512-$(openssl dgst -sha512 -binary "$work/si.tgz" | base64 | tr -d '\n')"
[ "$got" = "$integrity" ] || { echo "simple-icons $version: integrity mismatch" >&2; exit 1; }
tar -xzf "$work/si.tgz" -C "$work" package/data/simple-icons.json $(for s in $slugs; do printf 'package/icons/%s.svg ' "$s"; done)

python3 -I - "$work/package" "$version" "$root" $slugs <<'PY'
import json, re, sys
pkg, version, root, slugs = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
data = {(i.get("slug") or ""): i for i in json.load(open(f"{pkg}/data/simple-icons.json"))}
licence_urls = {
    "CC-BY-3.0": "https://creativecommons.org/licenses/by/3.0/",
    "CC-BY-SA-2.5": "https://creativecommons.org/licenses/by-sa/2.5/",
    "CC-BY-SA-3.0": "https://creativecommons.org/licenses/by-sa/3.0/",
    "CC-BY-SA-4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
}
# Who to credit, from each project's own logo page: CC BY and CC BY-SA
# require naming the creator.
attribution = {
    "git": "Git Logo by Jason Long (git-scm.com/community/logos)",
    "neovim": "Neovim logo by Jason Long (neovim.io, which states CC BY 3.0)",
    "ruby": "The Ruby logo is Copyright (c) 2006, Yukihiro Matsumoto (ruby-lang.org/en/about/logo)",
    "rust": "The Rust logo is owned by the Rust Foundation (foundation.rust-lang.org, CC BY)",
    "zig": "Official Zig project logo (github.com/ziglang/logo)",
    "php": "PHP logo by Colin Viebrock (php.net/download-logos.php)",
}
swift, notice = [], []
for slug in slugs:
    svg = open(f"{pkg}/icons/{slug}.svg").read()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    assert len(paths) == 1 and 'viewBox="0 0 24 24"' in svg, slug
    i = data[slug]
    lic = (i.get("license") or {}).get("type")
    assert lic is None or lic == "CC0-1.0" or lic in licence_urls, f"{slug}: {lic} needs review"
    assert lic not in licence_urls or slug in attribution, f"{slug}: {lic} needs an attribution"
    assert not re.search(r'["\\]', i["title"] + paths[0]), f"{slug}: quote or backslash in Swift literal"
    swift.append(f'        "{slug}": BrandIcon(title: "{i["title"]}", hex: 0x{i["hex"]}, path: "{paths[0]}"),')
    shown = lic or "no licence recorded for this icon (the Simple Icons collection is CC0-1.0)"
    line = f'{i["title"]} ({slug}): {shown}. Source: {i.get("source", "")}'
    if lic in licence_urls:
        line += f"\n  {attribution[slug]}.\n  Licence: {licence_urls[lic]}. Shipped unmodified, drawn in one colour."
    notice.append(line)

with open(f"{root}/apps/macos/Sources/HiveCore/Icons.generated.swift", "w") as f:
    f.write(f"""// Generated by script/icons.sh from Simple Icons {version}. Do not edit.
// Licences per icon: script/notices/icons.txt.

extension BrandIcon {{
    public static let all: [String: BrandIcon] = [
{chr(10).join(swift)}
    ]
}}
""")
with open(f"{root}/script/notices/icons.txt", "w") as f:
    f.write(f"""Program icons
=============

Hive.app shows these logos only to name the program running in a pane. They
come from Simple Icons {version} (https://simpleicons.org, CC0-1.0 as a
collection). They are not covered by hive's MIT licence: each logo keeps its
own licence, below, and remains a trademark of its owner.

""" + "\n".join(notice) + "\n")
PY
echo "icons: $(echo $slugs | wc -w | tr -d ' ') from simple-icons $version"
